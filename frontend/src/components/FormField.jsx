// Renders ONE field from its configuration object (see PHASE2_HANDOFF.md).
// Supported inputType values: text, email, tel, number, date, select, textarea, checkbox.
export default function FormField({ field, value, error, onChange, onBlur, options = [], disabled = false, hint = '' }) {
  const { fieldName, label, inputType, placeholder, isRequired } = field;
  const rules = field.validationRules || {};
  const readOnly = Boolean(rules.readOnly);
  const id = `field-${fieldName}`;
  const errorId = `${id}-error`;
  const common = {
    id,
    name: fieldName,
    disabled,
    'aria-invalid': error ? 'true' : undefined,
    'aria-describedby': error ? errorId : undefined,
    onBlur: () => onBlur && onBlur(fieldName),
  };
  const handle = (e) => onChange(fieldName, e.target.value);

  let control;
  if (inputType === 'select') {
    control = (
      <select {...common} value={value} onChange={handle}>
        <option value="">{hint || placeholder || 'Select…'}</option>
        {options.map((o) => (
          <option key={o.value} value={o.value}>
            {o.label}
          </option>
        ))}
      </select>
    );
  } else if (inputType === 'textarea') {
    control = (
      <textarea {...common} rows={3} value={value} placeholder={placeholder} maxLength={rules.maxLength} onChange={handle} />
    );
  } else if (inputType === 'checkbox') {
    control = (
      <label className="checkbox">
        <input
          {...common}
          type="checkbox"
          checked={Boolean(value)}
          onChange={(e) => onChange(fieldName, e.target.checked)}
        />
        <span>{label}</span>
      </label>
    );
  } else {
    control = (
      <input
        {...common}
        type={inputType}
        value={value}
        placeholder={placeholder}
        readOnly={readOnly}
        step={inputType === 'number' ? rules.step || 'any' : undefined}
        onChange={handle}
      />
    );
  }

  const full = inputType === 'textarea' || inputType === 'checkbox';
  return (
    <div className={`field${full ? ' field--full' : ''}${error ? ' field--error' : ''}`}>
      {inputType !== 'checkbox' && (
        <label htmlFor={id}>
          {label}
          {isRequired && !readOnly && <span className="required" aria-hidden="true"> *</span>}
        </label>
      )}
      {control}
      {readOnly && <small className="field__hint">Generated by the system; cannot be edited.</small>}
      {error && (
        <small id={errorId} className="field__error">
          {error}
        </small>
      )}
    </div>
  );
}
