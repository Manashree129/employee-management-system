-- Employee Management System - PostgreSQL schema (mirrors employees/migrations/0001_initial.py)
-- Run on an EMPTY database. See README "Initialization order".
BEGIN;

CREATE TABLE departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_departments_is_active ON departments (is_active);

CREATE TABLE designations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id  BIGINT       NOT NULL REFERENCES departments (id) ON DELETE CASCADE,
    name           VARCHAR(100) NOT NULL,
    CONSTRAINT uq_designation_department_name UNIQUE (department_id, name)
);
CREATE INDEX designations_department_id_idx ON designations (department_id);

CREATE TABLE lookup_values (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category       VARCHAR(50)  NOT NULL,
    value          VARCHAR(50)  NOT NULL,
    label          VARCHAR(100) NOT NULL,
    display_order  SMALLINT     NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_lookup_category_value UNIQUE (category, value)
);
CREATE INDEX idx_lookup_category_order ON lookup_values (category, display_order);

CREATE TABLE employees (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code      VARCHAR(20)   NOT NULL UNIQUE,
    first_name         VARCHAR(50)   NOT NULL,
    last_name          VARCHAR(50)   NOT NULL,
    email              VARCHAR(254)  NOT NULL UNIQUE,
    mobile_number      VARCHAR(10)   NOT NULL,
    date_of_birth      DATE          NOT NULL,
    gender             VARCHAR(10)   NOT NULL,
    department_id      BIGINT        NOT NULL REFERENCES departments (id) ON DELETE RESTRICT,
    designation_id     BIGINT        NOT NULL REFERENCES designations (id) ON DELETE RESTRICT,
    employment_type    VARCHAR(20)   NOT NULL,
    joining_date       DATE          NOT NULL,
    contract_end_date  DATE          NULL,
    salary             NUMERIC(12,2) NOT NULL,
    address            VARCHAR(250)  NOT NULL DEFAULT '',
    is_active          BOOLEAN       NOT NULL DEFAULT TRUE,
    is_deleted         BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_employee_salary_positive CHECK (salary > 0),
    CONSTRAINT chk_employee_mobile_10_digits CHECK (mobile_number ~ '^[0-9]{10}$'),
    CONSTRAINT chk_employee_gender CHECK (gender IN ('Male', 'Female', 'Other')),
    CONSTRAINT chk_employee_employment_type CHECK (employment_type IN ('Permanent', 'Contract', 'Intern')),
    CONSTRAINT chk_employee_contract_end_required CHECK (employment_type = 'Permanent' OR contract_end_date IS NOT NULL),
    CONSTRAINT chk_employee_contract_end_after_join CHECK (contract_end_date IS NULL OR contract_end_date > joining_date)
);
CREATE INDEX employees_department_id_idx  ON employees (department_id);
CREATE INDEX employees_designation_id_idx ON employees (designation_id);
CREATE INDEX idx_emp_dept_deleted   ON employees (department_id, is_deleted);
CREATE INDEX idx_emp_deleted_active ON employees (is_deleted, is_active);
CREATE INDEX idx_emp_first_last     ON employees (first_name, last_name);
CREATE INDEX idx_emp_joining_date   ON employees (joining_date);

CREATE TABLE form_field_configs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_name         VARCHAR(50)  NOT NULL,
    field_name        VARCHAR(50)  NOT NULL,
    label             VARCHAR(100) NOT NULL,
    input_type        VARCHAR(20)  NOT NULL,
    placeholder       VARCHAR(100) NOT NULL DEFAULT '',
    display_order     SMALLINT     NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    is_required       BOOLEAN      NOT NULL DEFAULT FALSE,
    validation_rules  JSONB        NOT NULL DEFAULT '{}'::jsonb,
    conditional_rules JSONB        NULL,
    options_source    VARCHAR(100) NOT NULL DEFAULT '',
    depends_on        VARCHAR(50)  NOT NULL DEFAULT '',
    default_value     JSONB        NULL,
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_formfield_form_field UNIQUE (form_name, field_name)
);
CREATE INDEX idx_formfield_form_order ON form_field_configs (form_name, display_order);

COMMIT;
